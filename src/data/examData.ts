export function parseMoneyValue(val: string | number | undefined): number {
  if (val === undefined || val === null) return 0;
  if (typeof val === 'number') return val;
  const cleaned = String(val).trim().replace(/^R\$\s*/i, '').replace(/\./g, '').replace(',', '.');
  const num = Number(cleaned);
  return Number.isFinite(num) ? num : 0;
}

export function formatCurrencyBRL(num: number): string {
  return num.toLocaleString('pt-BR', { style: 'currency', currency: 'BRL' });
}

export function isImagingExamWithContrast(description: string): boolean {
  const d = String(description || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase();
  
  const keywords = [
    'TOMOGRAF', 'ANGIOTOM', 'RESSON', 'RNM', 'ANGIO RM', 'ANGIORM', ' RM ', 
    'COLANGIO', 'URO-RM', 'URO RM', 'UROTOM', 'TC ', 'TC-', 'TC/', 'TC:', 'TAC '
  ];
  
  if (keywords.some(k => d.includes(k))) return true;
  if (d.startsWith('TC ') || d.startsWith('TC-') || d.startsWith('TC/') || d.startsWith('RM ') || d.startsWith('RM-') || d.startsWith('RNM ')) return true;
  return false;
}
